const done = load('plan', {});
const UI = { open: load('planOpen', 0) };

function render(root) {
  root.innerHTML = `
    <div class="kicker">практика · план</div>
    <h1 class="title-big">4 недели <span>по 25 минут</span></h1>
    <div class="pillrow">${SLOTS.map(([t, n]) => pill(`${t} · ${n}`, '#e8ecf3')).join(' ')}</div>
    ${WEEKS.map((w, wi) => {
      const cnt = Array.from({ length: 7 }, (_, d) => done[`${wi}-${d}`]).filter(Boolean).length;
      return `<div class="week" style="border-color:${UI.open === wi ? w.color : ''}">
        <div class="row sp" data-act="open" data-w="${wi}" style="cursor:pointer;margin:0;min-height:40px"><b style="color:${w.color}">${w.title}</b><small>${cnt}/7 дней</small></div>
        ${UI.open === wi ? `${w.items.map((it, i) => `<div class="plan-slot"><b>${SLOTS[i][0]}</b><div><b>${SLOTS[i][1]}.</b> ${it[1]} <button class="btn g sm" data-act="go" data-id="${it[0]}" style="margin-top:4px">Открыть →</button></div></div>`).join('')}
          <div class="daygrid">${Array.from({ length: 7 }, (_, d) => `<button type="button" class="${done[`${wi}-${d}`] ? 'done' : ''}" data-act="day" data-k="${wi}-${d}">${done[`${wi}-${d}`] ? '✓' : 'Д' + (d + 1)}</button>`).join('')}</div>` : ''}
      </div>`;
    }).join('')}
    <div class="card">
      <h3 style="margin-top:0">Как заниматься тихо в квартире</h3>
      <ul><li>Играй через Scarlett Solo в наушниках: в AmpliTube / Neural DSP перегруз не зависит от громкости — соседи ничего не слышат.</li>
      <li>Palm mute, хроматика и переменный штрих хорошо тренируются даже без усиления — по звуку струн слышно, где грязно.</li>
      <li>Лучше 25 минут каждый день, чем 3 часа раз в неделю: мышечная память закрепляется во сне.</li></ul>
    </div>
    <div class="card"><h3 style="margin-top:0">Что учить дальше</h3>
      ${NEXT.map(([t, d]) => `<p><b>${t}.</b> ${d}</p>`).join('')}
      ${info('Каждые 4 недели повторяй тест ритма и записывай темпы упражнений — прогресс должен быть виден в цифрах.')}
    </div>`;
}

export const page = {
  id: 'plan', title: 'План', section: 'practice',
  mount(el) {
    render(el);
    bind(el, {
      act: {
        open: b => { UI.open = +b.dataset.w; save('planOpen', UI.open); render(el); },
        day: b => { const k = b.dataset.k; done[k] = !done[k]; save('plan', done); render(el); },
        go: b => { try { location.hash = b.dataset.id; } catch (e) { } },
      },
    });
  },
};
